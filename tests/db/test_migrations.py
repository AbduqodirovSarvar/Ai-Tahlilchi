ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"


def alembic_config(db_path: Path) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.attributes["db_path"] = db_path
    config.attributes["configure_logger"] = False
    return config


@contextmanager
def connect(db_path: Path) -> Iterator[sqlite3.Connection]:
    """Plain sqlite3 connection that is committed and closed on exit."""
    with closing(sqlite3.connect(db_path)) as connection, connection:
        yield connection


def table_names(db_path: Path) -> set[str]:
    with connect(db_path) as connection:
        rows = connection.execute("SELECT name FROM sqlite_master WHERE type = 'table'")
        return {name for (name,) in rows}


def test_upgrade_downgrade_upgrade_round_trip(tmp_path: Path) -> None:
    db_path = tmp_path / "migrated.db"
    config = alembic_config(db_path)

    command.upgrade(config, "head")
    assert table_names(db_path) == set(Base.metadata.tables) | {"alembic_version"}

    command.downgrade(config, "base")
    assert table_names(db_path) == {"alembic_version"}

    command.upgrade(config, "head")
    assert table_names(db_path) == set(Base.metadata.tables) | {"alembic_version"}


