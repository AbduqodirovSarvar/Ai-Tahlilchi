"""Alembic migrations: upgrade, downgrade and parity with the ORM schema."""

import sqlite3
from collections.abc import Iterator
from contextlib import closing, contextmanager
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory

from app.config import get_settings
from app.db.schema import Base

ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"


def alembic_config(db_path: Path) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.attributes["db_path"] = db_path
    config.attributes["configure_logger"] = False
    return config


@contextmanager
def connect(db_path: Path) -> Iterator[sqlite3.Connection]:
    """Plain sqlite3 connection that is committed and closed on exit."""
    with closing(sqlite3.connect(db_path)) as connection, connection:
        yield connection


def table_names(db_path: Path) -> set[str]:
    with connect(db_path) as connection:
        rows = connection.execute("SELECT name FROM sqlite_master WHERE type = 'table'")
        return {name for (name,) in rows}


def test_upgrade_downgrade_upgrade_round_trip(tmp_path: Path) -> None:
    db_path = tmp_path / "migrated.db"
    config = alembic_config(db_path)

    command.upgrade(config, "head")
    assert table_names(db_path) == set(Base.metadata.tables) | {"alembic_version"}

    command.downgrade(config, "base")
    assert table_names(db_path) == {"alembic_version"}

    command.upgrade(config, "head")
    assert table_names(db_path) == set(Base.metadata.tables) | {"alembic_version"}


def test_migrations_match_the_orm_schema(tmp_path: Path) -> None:
    config = alembic_config(tmp_path / "check.db")
    command.upgrade(config, "head")
    # Raises AutogenerateDiffsDetected if the models changed without a migration.
    command.check(config)


def test_migrations_run_on_a_database_with_data(tmp_path: Path) -> None:
    db_path = tmp_path / "with_data.db"
    config = alembic_config(db_path)
    command.upgrade(config, "head")
    with connect(db_path) as connection:
        connection.execute(
            "INSERT INTO leagues (sport, source, external_id, name, created_at, updated_at)"
            " VALUES ('football', 'src', 'E0', 'EPL', '2024-01-01', '2024-01-01')"
        )
    command.upgrade(config, "head")  # re-running is a no-op that keeps the data
    with connect(db_path) as connection:
        assert connection.execute("SELECT count(*) FROM leagues").fetchone() == (1,)
    command.downgrade(config, "base")
    assert table_names(db_path) == {"alembic_version"}


def test_single_linear_history() -> None:
    scripts = ScriptDirectory.from_config(Config(str(ALEMBIC_INI)))
    assert len(scripts.get_heads()) == 1
    for revision in scripts.walk_revisions():
        module = revision.module
        assert callable(module.upgrade)
        assert callable(module.downgrade)


def test_database_path_comes_from_settings_by_default(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    db_path = tmp_path / "from_settings.db"
    monkeypatch.setenv("DB_PATH", str(db_path))
    get_settings.cache_clear()
    try:
        config = Config(str(ALEMBIC_INI))
        config.attributes["configure_logger"] = False
        command.upgrade(config, "head")
    finally:
        get_settings.cache_clear()
    assert "fixtures" in table_names(db_path)


def test_offline_mode_renders_sql(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    command.upgrade(alembic_config(tmp_path / "offline.db"), "head", sql=True)
    sql = capsys.readouterr().out
    assert "CREATE TABLE fixtures" in sql
    assert not (tmp_path / "offline.db").exists()
